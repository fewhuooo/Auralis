function buildCatalog() {
  const catalog = new Map()
  const invalidCounts = []
  for (const [subjectName, base] of Object.entries(KNOWLEDGE_CATALOG)) {
    const extras = (SUPPLEMENTAL_TOPICS[subjectName] || []).map(([title, note]) => ({
      title,
      content: `### ${title}\n\n${note}\n\n**自测：**解释核心条件，并给出一个${subjectName}中的应用或反例。`
    }))
    const blocks = [...base.blocks, ...extras]
    const titles = new Set(blocks.map((block) => block.title))
    if (titles.size !== 30) {
      invalidCounts.push(`${subjectName}: ${titles.size}`)
    }
    catalog.set(subjectName, blocks)
  }
  if (Object.keys(SUPPLEMENTAL_TOPICS).length !== Object.keys(KNOWLEDGE_CATALOG).length) {
    throw new Error('Supplemental topic list does not cover every seeded subject.')
  }
  if (invalidCounts.length > 0) {
    throw new Error(`Seed catalog must contain 30 unique titles per subject; found ${invalidCounts.join(', ')}.`)
  }
  return catalog
}

async function getAllItems(path, token) {
  const items = []
  let cursor = null
  do {
    const url = new URL(path)
    url.searchParams.set('limit', '200')
    if (cursor) url.searchParams.set('cursor', cursor)
    const page = await getJson(url.toString(), token)
    items.push(...page.items)
    cursor = page.hasMore ? page.nextCursor : null
  } while (cursor)
  return items
}

async function main() {
  const catalog = buildCatalog()
  console.log(`1. Authenticating as ${testUsername}...`)
  const auth = await postJson(`${baseUrl}/api/auth/login`, {
    username: testUsername,
    password: testPassword,
    clientDeviceKey: deviceKey,
    deviceName: 'Codex 测试设备',
    platform: 'WINDOWS'
  })
  const token = auth.tokens.accessToken
  console.log(`Authenticated as ${auth.user.id}`)

  console.log('2. Fetching subjects...')
  const subjects = await getAllItems(`${baseUrl}/api/subjects`, token)
  const subjectMap = new Map(subjects.map((s) => [s.name, s.id]))
  console.log(`Found ${subjectMap.size} subjects.`)

  const existingBlocks = await getAllItems(`${baseUrl}/api/knowledge-blocks`, token)
  const existingBySubject = new Map()
  for (const block of existingBlocks) {
    if (!existingBySubject.has(block.subjectId)) existingBySubject.set(block.subjectId, [])
    existingBySubject.get(block.subjectId).push(block)
  }

  let createdTotal = 0
  const finalCounts = new Map()

  for (const [subjectName, blocks] of catalog) {
    const subjectId = subjectMap.get(subjectName)
    if (!subjectId) {
      throw new Error(`Subject not found in DB: ${subjectName}`)
    }

    const subjectBlocks = existingBySubject.get(subjectId) || []
    const existingTitles = new Set(subjectBlocks.map((block) => block.title))
    let activeCount = subjectBlocks.length
    let createdForSubject = 0

    for (const blk of blocks) {
      if (activeCount >= 30) break
      if (existingTitles.has(blk.title)) continue
      await postJson(`${baseUrl}/api/knowledge-blocks`, {
        baseVersion: 0,
        subjectId,
        sourceId: null,
        title: blk.title,
        content: blk.content,
        colorOverride: null
      }, token)
      existingTitles.add(blk.title)
      activeCount++
      createdForSubject++
      createdTotal++
    }

    if (activeCount < 30) throw new Error(`${subjectName} has only ${activeCount} active knowledge blocks after seeding.`)
    finalCounts.set(subjectName, activeCount)
    console.log(`${subjectName}: created ${createdForSubject}, final ${activeCount}/30.`)
  }

  const verifiedBlocks = await getAllItems(`${baseUrl}/api/knowledge-blocks`, token)
  for (const [subjectName, subjectId] of subjectMap) {
    const count = verifiedBlocks.filter((block) => block.subjectId === subjectId).length
    if (count < 30) throw new Error(`${subjectName} verification failed: expected at least 30, found ${count}.`)
    finalCounts.set(subjectName, count)
  }

  console.log(`\n========================================`)
  console.log(`Knowledge block seeding complete.`)
  console.log(`Created ${createdTotal} blocks; verified ${verifiedBlocks.length} total across ${subjectMap.size} subjects.`)
  console.log([...finalCounts.entries()].map(([name, count]) => `${name}=${count}`).join(', '))
  console.log(`All seed blocks have sourceId=null; no assets or sources were created.`)
  console.log(`========================================`)
}

main().catch((err) => {
  console.error('Seeding failed:', err.message || err)
  process.exit(1)
})

